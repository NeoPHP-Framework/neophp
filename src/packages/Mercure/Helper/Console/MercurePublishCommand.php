<?php

declare(strict_types=1);

namespace NeoPHP\Package\Mercure\Helper\Console;

use NeoPHP\Package\Mercure\Exception\MercureException;
use NeoPHP\Package\Mercure\MercureManagerInterface;
use NeoPHP\Package\Mercure\Model\Update;
use NeoPHP\Process\Console\Attribute\AsCommand;
use NeoPHP\Process\Console\Contract\AbstractConsole;
use NeoPHP\Process\Console\Contract\InputInterface;
use NeoPHP\Process\Console\Contract\OutputInterface;
use NeoPHP\Process\Console\IO\InputArgument;
use NeoPHP\Process\Console\IO\InputOption;

/**
 * @internal
 */
#[AsCommand(name: 'mercure:publish', description: 'Publishes an update to the Mercure hub')]
class MercurePublishCommand extends AbstractConsole
{
    public function __construct(protected MercureManagerInterface $mercure)
    {
    }

    protected function configure(InputInterface $input, OutputInterface $output): void
    {
        $input->addArgument('topic', InputArgument::REQUIRED, 'The topic of the update', null, 'Topic of the update');
        $input->addArgument('data', InputArgument::OPTIONAL, 'The data sent to the subscribers', '');
        $input->addOption('private', null, InputOption::VALUE_NONE, 'Sends the update only to the authorized subscribers');
        $input->addOption('id', null, InputOption::VALUE_REQUIRED, 'The id of the event (generated by the hub by default)');
        $input->addOption('type', null, InputOption::VALUE_REQUIRED, 'The type of the event');
        $input->addOption('retry', null, InputOption::VALUE_REQUIRED, 'The reconnection time asked to the subscribers, in milliseconds');
        $this->setHelp('Useful to check the configuration of the hub: open a page subscribed to the topic, then publish an update.');
        $this->addExample('mercure:publish https://example.com/books/1 \'{"title":"Neo"}\'');
        $this->addExample('mercure:publish chat/42 "Hello" --private --type=message');
    }

    protected function do(InputInterface $input, OutputInterface $output): int
    {
        $retry = $input->getOption('retry');

        try {
            $id = $this->mercure->publish(new Update(
                (string) $input->getArgument('topic'),
                (string) $input->getArgument('data'),
                (bool) $input->getOption('private'),
                $input->getOption('id') !== null ? (string) $input->getOption('id') : null,
                $input->getOption('type') !== null ? (string) $input->getOption('type') : null,
                $retry !== null ? (int) $retry : null,
            ));
        } catch (MercureException $exception) {
            $output->error($exception->getMessage());

            return self::FAILURE;
        }

        $output->newLine();
        $output->writeln(sprintf('  <success>published</success>  %s', $id));
        $output->success(sprintf('The update was published to %s.', $this->mercure->getUrl()));

        return self::SUCCESS;
    }
}