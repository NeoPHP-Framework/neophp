<?php

declare(strict_types=1);

namespace NeoPHP\Package\Mercure\Model;

use JsonException;
use NeoPHP\Package\Mercure\Exception\MercureException;

class Update
{
    protected array $topics;

    /**
     * @param string|array<array-key, mixed> $topics The topic, or the topics (non-empty strings), of the update (an IRI or any string)
     * @param string $data The data sent to the subscribers (the "data" of the server-sent event)
     * @param bool $private Sends the update only to the subscribers authorized for one of its topics
     * @param string|null $id The id of the event, generated by the hub when null
     * @param string|null $type The type of the event (the "event" field of the server-sent event)
     * @param int|null $retry The reconnection time asked to the subscribers, in milliseconds
     * @throws MercureException When there is no topic, a topic is empty or the retry is negative
     */
    public function __construct(
        string|array $topics,
        protected string $data = '',
        protected bool $private = false,
        protected ?string $id = null,
        protected ?string $type = null,
        protected ?int $retry = null,
    ) {
        $topics = is_array($topics) ? array_values($topics) : [$topics];

        if ($topics === []) {
            throw new MercureException('A Mercure update needs at least one topic.');
        }

        foreach ($topics as $topic) {
            if (!is_string($topic) || trim($topic) === '') {
                throw new MercureException('The topics of a Mercure update must be non-empty strings, {type} given.', 0, null, ['type' => get_debug_type($topic)]);
            }
        }

        if ($retry !== null && $retry < 0) {
            throw new MercureException('The retry of a Mercure update must be a positive number of milliseconds, {retry} given.', 0, null, ['retry' => $retry]);
        }

        $this->topics = $topics;
    }

    /**
     * Creates an update whose data is encoded as JSON.
     *
     * @param string|list<string> $topics The topic, or the topics, of the update
     * @param mixed $data The value encoded as JSON
     * @param bool $private Sends the update only to the authorized subscribers
     * @param string|null $id The id of the event
     * @param string|null $type The type of the event
     * @param int|null $retry The reconnection time, in milliseconds
     * @return static The update
     * @throws MercureException When the value cannot be encoded or the topics are invalid
     */
    public static function json(string|array $topics, mixed $data, bool $private = false, ?string $id = null, ?string $type = null, ?int $retry = null): static
    {
        try {
            $json = json_encode($data, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION);
        } catch (JsonException $exception) {
            throw new MercureException('The data of the Mercure update cannot be encoded as JSON: {error}.', 0, $exception, ['error' => $exception->getMessage()]);
        }

        return new static($topics, $json, $private, $id, $type, $retry);
    }

    /**
     * @return list<string>
     */
    public function getTopics(): array
    {
        return $this->topics;
    }

    public function getData(): string
    {
        return $this->data;
    }

    public function isPrivate(): bool
    {
        return $this->private;
    }

    public function getId(): ?string
    {
        return $this->id;
    }

    public function getType(): ?string
    {
        return $this->type;
    }

    public function getRetry(): ?int
    {
        return $this->retry;
    }

    /**
     * Returns the fields of the publication request, in the order expected by the hub.
     *
     * @return list<array{0: string, 1: string}> The name and the value of every field (a topic per "topic" field)
     */
    public function toFields(): array
    {
        $fields = [];

        foreach ($this->topics as $topic) {
            $fields[] = ['topic', $topic];
        }

        $fields[] = ['data', $this->data];

        if ($this->private) {
            $fields[] = ['private', 'on'];
        }

        if ($this->id !== null) {
            $fields[] = ['id', $this->id];
        }

        if ($this->type !== null) {
            $fields[] = ['type', $this->type];
        }

        if ($this->retry !== null) {
            $fields[] = ['retry', (string) $this->retry];
        }

        return $fields;
    }
}