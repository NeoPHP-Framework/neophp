<?php

declare(strict_types=1);

namespace NeoPHP\Package\QrCode;

use NeoPHP\Package\QrCode\Exception\QrCodeException;
use NeoPHP\Package\QrCode\Model\QrCode;
use NeoPHP\Package\QrCode\Model\ReadResult;

interface QrCodeManagerInterface
{
    /**
     * Creates a QR code holding a text (URL, identifier, any string).
     *
     * @param array<string, mixed> $options size, margin, error_correction, foreground, background, logo, logo_size
     * code (true or a lifetime in seconds: registers a short code typed when the QR code cannot be scanned)
     * @throws QrCodeException When an option is invalid
     */
    public function create(string $content, array $options = []): QrCode;

    /**
     * QR code holding data signed with APP_SECRET: nobody can forge or modify it. A short code is always registered.
     *
     * @param mixed $data
     * @param int|null $rotate Validity in seconds of a code that changes regularly (e.g. 30 for a ticket: a screenshot is quickly useless)
     * @param int|null $ttl Lifetime in seconds when the code does not rotate, null = signed.ttl of the configuration (null there = never expires)
     * @param bool $once The code is refused after its first valid read
     * @param array<string, mixed> $options Display options of create()
     *
     * @return QrCode
     * @throws QrCodeException When APP_SECRET is empty or the data cannot be encoded in JSON
     */
    public function signed(mixed $data, ?int $rotate = null, ?int $ttl = null, bool $once = false, array $options = []): QrCode;

    /**
     * QR code opening a Wi-Fi network.
     *
     * @param string $encryption WPA, WEP or nopass
     */
    public function wifi(string $ssid, ?string $password = null, string $encryption = 'WPA', bool $hidden = false, array $options = []): QrCode;

    /**
     * QR code adding a contact: name, phone, email, organization, title, url, address, note.
     *
     * @param array<string, string> $contact
     */
    public function vcard(array $contact, array $options = []): QrCode;

    /**
     * QR code opening a new e-mail.
     */
    public function email(string $to, ?string $subject = null, ?string $body = null, array $options = []): QrCode;

    /**
     * QR code calling a phone number.
     */
    public function phone(string $number, array $options = []): QrCode;

    /**
     * QR code writing an SMS.
     */
    public function sms(string $number, ?string $message = null, array $options = []): QrCode;

    /**
     * QR code opening a position in the map application.
     */
    public function geo(float $latitude, float $longitude, array $options = []): QrCode;

    /**
     * QR code holding JSON.
     *
     * @throws QrCodeException When the data cannot be encoded in JSON
     */
    public function json(mixed $data, array $options = []): QrCode;

    /**
     * Registers the short code of a content and returns it (e.g. 7Q2K-4MXA): read() accepts it instead of the QR code.
     *
     * @param int|null $ttl Seconds during which it can be typed, null = code.ttl of the configuration
     *
     * @throws QrCodeException When no cache pool is available or APP_SECRET is empty
     */
    public function code(string $content, ?int $ttl = null): string;

    /**
     * Reads what a reader scanned or what was typed by hand: the content of a QR code or its short code.
     * A signed content is verified (signature, expiration, single use).
     *
     * @param string|null $source qr (scanned: never read as a short code), code (typed: only a short code) or null (guessed)
     */
    public function read(string $input, ?string $source = null): ReadResult;

    /**
     * URL of the image of a QR code, served by the package route and kept in the cache.
     *
     * @param string $format svg or png
     *
     * @throws QrCodeException When the format or an option is invalid, or no cache pool is available
     */
    public function imageUrl(string $content, array $options = [], string $format = 'svg'): string;

    /**
     * QR code of an image URL generated by imageUrl().
     *
     * @return QrCode|null Null when the key is unknown or expired
     */
    public function fromImageKey(string $key): ?QrCode;

    /**
     * URL path of the routes of the package (/_qr by default).
     */
    public function getPath(): string;

    /**
     * Path of the JavaScript file of the reader (<neo-qr-reader> element).
     */
    public function getReaderScript(): string;

    /**
     * URL of the JavaScript file of the reader, served by the package route.
     */
    public function getReaderScriptUrl(): string;

    /**
     * Configuration of config/packages/qr_code.yaml with the defaults.
     *
     * @return array<string, mixed>
     */
    public function getConfig(): array;
}